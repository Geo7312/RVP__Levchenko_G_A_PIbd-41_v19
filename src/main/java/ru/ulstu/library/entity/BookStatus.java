package ru.ulstu.library.entity;

/**
 * Статус книги в рамках предметной области варианта №19:
 * учёт книг и читателей в библиотеке.
 */
public enum BookStatus {
    /** Книга находится в библиотеке (на полке), свободна. */
    IN_LIBRARY,
    /** Книга выдана читателю на руки. */
    ON_HANDS,
    /** Книга выдана для чтения в читальном зале. */
    IN_READING_ROOM
}
